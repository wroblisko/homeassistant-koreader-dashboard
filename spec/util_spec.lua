local util = require("homedash_util")

describe("homedash_util", function()
    describe("clamp", function()
        it("returns the value when it is inside the range", function()
            assert.are.equal(5, util.clamp(5, 0, 10))
            assert.are.equal(1.5, util.clamp(1.5, 0, 3))
        end)

        it("clamps to the ends of the range", function()
            assert.are.equal(0, util.clamp(-1, 0, 10))
            assert.are.equal(10, util.clamp(11, 0, 10))
            assert.are.equal(0, util.clamp(0, 0, 10))
            assert.are.equal(10, util.clamp(10, 0, 10))
        end)
    end)

    describe("format_temp", function()
        it("uses a Polish decimal comma and a degree sign", function()
            assert.are.equal("4,2°", util.format_temp(4.2))
            assert.are.equal("4,0°", util.format_temp(4))
            assert.are.equal("0,0°", util.format_temp(0))
            assert.are.equal("-3,5°", util.format_temp(-3.5))
        end)

        it("rounds to one decimal", function()
            assert.are.equal("4,2°", util.format_temp(4.24))
            assert.are.equal("4,3°", util.format_temp(4.26))
        end)

        it("accepts a numeric string", function()
            assert.are.equal("4,2°", util.format_temp("4.2"))
        end)

        it("renders an em dash when the value is missing", function()
            assert.are.equal("—", util.format_temp(nil))
            assert.are.equal("—", util.format_temp("unavailable"))
            assert.are.equal("—", util.format_temp("unknown"))
            assert.are.equal("—", util.format_temp("nope"))
        end)
    end)
end)

describe("homedash_util.actions_enabled", function()
    local u = require("homedash_util")
    it("is disabled only by the exact string off", function()
        assert.is_false(u.actions_enabled("off"))
        assert.is_true(u.actions_enabled(nil))
        assert.is_true(u.actions_enabled(""))
        assert.is_true(u.actions_enabled("on"))
        assert.is_true(u.actions_enabled("OFF"))
    end)
end)
